n = int(input("请输入一个数:"))
a = n % 10 #个位
b = n // 10 % 10 #十位
c = n // 100 % 10 #百位
d = n // 1000 % 10 #千位
e = n // 10000 % 10 #万位
if(n < 10): #只有一位数
    print(f"是一个1位数: {n}")
elif(n < 100):
    print(f"是一个2位数: {a} {b}")
elif(n < 1000):
    print(f"是一个3位数: {a} {b} {c}")
elif(n < 10000):
    print(f"是一个4位数: {a} {b} {c} {d}")
elif(n < 100000):
    print(f"是一个5位数: {a} {b} {c} {d} {e}")